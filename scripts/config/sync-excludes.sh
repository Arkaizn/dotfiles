#!/usr/bin/env bash
# What the sync scripts (update.sh, push.sh, check.sh) leave alone.
# One list for all three, so a new per-device file only needs adding here.
# Paths are relative to ~/.config (and .config/ in the repo).

# Per-device files: never pushed, never overwritten by update.sh.
# The repo keeps a neutral default of each that update.sh copies in only when
# the file is missing (fresh install) — e.g. niri errors on a missing include.
# shellcheck disable=SC2034  # used by the scripts that source this file
DEVICE_FILES=(
    "custom/"                               # machine-specific binds, scripts, variables
    "kitty/current-theme.conf"              # generated by the theme
    "niri/config/layout.kdl"                # border gradient colors (niri-colors.sh)
    "niri/config/output.kdl"                # monitors
    "hypr/hyprland/monitors.lua"            # monitors (Hyprland)
    "hypr/hyprlock/hyprlock.sh"
    # quickshell settings app
    "quickshell/settings.json"              # shell / niri / Hyprland / monitor / calendar settings
    "niri/config/quickshell.kdl"            # niri overrides written by the settings app
    "niri/config/quickshell-outputs.kdl"    # monitor setup written by the settings app
    "hypr/quickshell.lua"                   # Hyprland overrides written by the settings app
    "hypr/quickshell-monitors.lua"          # monitor setup written by the settings app (Hyprland)
    # secrets
    "wayvnc/config"                         # VNC password — repo has config.example
)

# Never pushed into the repo (junk, secrets, generated or retired files).
# shellcheck disable=SC2034
NEVER_PUSH=(
    "*.bak*"                                # backups (config.kdl.bak-settings, …)
    "__pycache__/"
    "*.pyc"
    "cava"
    "wal/templates/Colors.qml"              # retired: quickshell reads ~/.cache/wal/colors.json now
    "*.example"                             # repo-only templates (excluded = also safe from --delete)
)
